"""The auto-palette tool: the shipped table, the gates it answers to, and the
generators for whatever gets designed next.

VERIFY-FIRST, and that is the lesson this file carries. The sixteen
theme-named palettes in `tangent-ui/src/mixer_panel.rs` were generated by
variants of this script that never got committed -- the commit that landed the
per-palette masters managed to commit only a `__pycache__` byte-code file --
so the exact generators are gone and the shipped values are FROZEN DATA. They
are embedded below, and `--check` proves three things about them: the copy
here matches the Rust byte for byte, the emitted Rust for every run matches
the file verbatim, and every value still clears the gates its commit message
promised. Design work for NEW palettes happens here, in Python, against those
same gates, BEFORE any Rust is written; `STRIP_COLORS` itself is append-only.

The governing rule has not changed: a strip colour is a whole painted surface
with small text printed straight onto it, so every palette colour must be
dark enough that the light ink wins AND clears 4.5:1 against it. That is a
luminance ceiling, which is what TONES encodes -- and a chroma ceiling rides
beside it, because equal luminance is not equal vividness.

    --check      validate the embedded table against the Rust and the gates
                 (also the default when no flag is given)
    --emit       print the shipped runs as Rust, byte-identical to the file
    --legacy     the eight retired abstract palettes (pre theme-named runs)
    --gradients  the monotone-ramp model that was explored and never shipped
    --dark       the factory themes designed in this file, held to the ported
                 Rust sweeps (the dark two, and Silverface)
    --silverface the Silverface run re-derived from its families and proved
                 equal to the pinned bytes, plus the whole-desk gates
"""
import colorsys
import re
from pathlib import Path

INK_LIGHT = (0xE8, 0xDC, 0xC0)
INK_DARK = (0x1A, 0x1A, 0x1A)


def _ch(v):
    v = v / 255.0
    return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4


def luminance(c):
    return 0.2126 * _ch(c[0]) + 0.7152 * _ch(c[1]) + 0.0722 * _ch(c[2])


def contrast(a, b):
    x, y = luminance(a), luminance(b)
    hi, lo = max(x, y), min(x, y)
    return (hi + 0.05) / (lo + 0.05)


def wants_light_ink(c):
    return contrast(c, INK_LIGHT) > contrast(c, INK_DARK)


def ink_contrast(c):
    return contrast(c, INK_LIGHT if wants_light_ink(c) else INK_DARK)


def _lab(c):
    r, g, b = (_ch(v) for v in c)
    x = r * 0.4124 + g * 0.3576 + b * 0.1805
    y = r * 0.2126 + g * 0.7152 + b * 0.0722
    z = r * 0.0193 + g * 0.1192 + b * 0.9505

    def f(t):
        return t ** (1 / 3) if t > 0.008856 else (7.787 * t + 16 / 116)

    fx, fy, fz = f(x / 0.95047), f(y / 1.0), f(z / 1.08883)
    return (116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz))


def de(a, b):
    return sum((x - y) ** 2 for x, y in zip(_lab(a), _lab(b))) ** 0.5


def hexs(c):
    return f"#{c[0]:02x}{c[1]:02x}{c[2]:02x}"


# Four tones, named by the luminance they land on. The top one sits under
# the 0.119 ceiling where 4.5:1 against the ivory ink runs out.
TONES = [0.016, 0.038, 0.068, 0.104]


def chroma(c):
    _, a, b = _lab(c)
    return (a * a + b * b) ** 0.5


def _at_luminance(hue, sat, target):
    lo, hi = 0.0, 1.0
    for _ in range(40):
        mid = (lo + hi) / 2
        r, g, b = colorsys.hsv_to_rgb(hue / 360.0, sat, mid)
        c = (round(r * 255), round(g * 255), round(b * 255))
        if luminance(c) < target:
            lo = mid
        else:
            hi = mid
    r, g, b = colorsys.hsv_to_rgb(hue / 360.0, sat, (lo + hi) / 2)
    return (round(r * 255), round(g * 255), round(b * 255))


# The chroma ceiling, and the reason this generator does two things at once.
#
# **Equal luminance is not equal vividness.** Blue contributes almost nothing
# to luminance, so a violet forced onto the same luminance as an ochre has to
# climb to #7736c1 to get there -- and next to muted earth tones it reads as
# a neon sign somebody left on. That is precisely the "incoherent" the owner
# saw. So the hue is held to a chroma ceiling as well: saturation comes down
# until the colour is no more colourful than the rest of its set, and the
# luminance is re-solved underneath it.
CHROMA_MAX = 42.0


def make(hue, sat, tone, cmax=CHROMA_MAX, lum=None):
    """A colour at `hue` sitting on TONES[tone], no more vivid than `cmax`.

    `lum` overrides the tone with an explicit luminance, which is what the
    gradients need: a ramp does not land on four named steps, it lands
    wherever it is along the ramp.
    """
    hue = hue % 360.0
    target = TONES[tone] if lum is None else lum
    c = _at_luminance(hue, sat, target)
    while chroma(c) > cmax and sat > 0.06:
        sat -= 0.02
        c = _at_luminance(hue, sat, target)
    return c


