def parse_rust():
    """STRIP_COLORS and the PALETTES index table, straight out of the Rust."""
    src = MIXER_RS.read_text()
    body = re.search(r"pub const STRIP_COLORS[^=]*=\s*\[(.*?)\n\];", src, re.S)
    cols = [
        tuple(int(x, 16) for x in t)
        for t in re.findall(
            r"\(\s*0x([0-9a-fA-F]{2}),\s*0x([0-9a-fA-F]{2}),\s*0x([0-9a-fA-F]{2})\s*\)",
            body.group(1),
        )
    ]
    pals = [
        (name, int(base), int(mat), int(ext), int(ext2))
        for name, base, mat, ext, ext2 in re.findall(
            r'Palette \{ name: "(\w+)", base: (\d+), master_at: (\d+), '
            r'ext: (\d+), ext2: (\d+) \}',
            src,
        )
    ]
    return src, cols, pals


